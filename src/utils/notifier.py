import os
from github import Github

class Notifier:
    def __init__(self, config):
        self.config = config
        self.notification_type = config["notifications"].get("type", "github_issue")
        # The GITHUB_TOKEN is provided by GitHub Actions automatically
        self.github_token = os.getenv("GITHUB_TOKEN")

    def send_alert(self, alert):
        """
        Sends a notification alert.
        alert: dict containing {office, vacancies, tier, urgency, link}
        """
        if self.notification_type == "github_issue":
            self._send_github_issue(alert)
        else:
            print(f"[MOCK ALERT] {alert['urgency']} Priority: {alert['office']} - {alert['vacancies']} vacancies found. Tier: {alert['tier']}")

    def _send_github_issue(self, alert):
        """Creates a GitHub Issue in the current repository."""
        if not self.github_token:
            print("GITHUB_TOKEN not found in environment. Falling back to mock alert.")
            print(f"[MOCK ALERT] {alert['urgency']} Priority: {alert['office']} - {alert['vacancies']} vacancies found.")
            return

        try:
            g = Github(self.github_token)
            # Use the repository name from config, fallback to env var
            repo_name = self.config["notifications"].get("repository", os.getenv("GITHUB_REPOSITORY", "erichchampion/office-vacancies"))
            repo = g.get_repo(repo_name)

            title = f"🚨 Vacancy Detected: {alert['office']}"

            # Construct detailed body
            body = (
                f"## {alert['office']}\n\n"
                f"- **Eligibility:** {alert['tier']}\n"
                f"- **Vacancies:** {alert['vacancies']} available\n"
                f"- **Urgency:** {alert['urgency']}\n"
                f"- **Link:** {alert.get('link', 'Check Candidate Watch')}\n\n"
                f"---\n"
                f"This issue was automatically generated by the Office Vacancy Detection System."
            )

            issue = repo.create_issue(title=title, body=body)
            print(f"Successfully created GitHub issue: {issue.html_url}")
        except Exception as e:
            print(f"Failed to create GitHub issue: {e}")
